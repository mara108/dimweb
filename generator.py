"""
Генератор кандидатов-диминутивов для русских существительных.

Архитектура:
    лемма -> pymorphy2 (род, тип основы) -> правила словообразования
    -> кандидаты с меткой суффикса -> подстановка коннотации из таблицы
    -> (следующий шаг, вне этого файла) LLM-фильтр подтверждает
       существование формы и уточняет коннотацию

Таблица коннотаций (SUFFIX_TABLE_PATH) собрана из академического
словообразовательного словаря и размечает суффиксы по трём типам
окраски: нейтральная, ласкательная, пренебрежительная.
"""

import json
import os
import pymorphy2

morph = pymorphy2.MorphAnalyzer()


def is_in_dictionary(word: str) -> bool:
    """
    Проверка, есть ли слово в словаре OpenCorpora (встроен в pymorphy2).

    Раньше здесь была проверка через methods_stack (any(...) по всем
    разборам на DictionaryAnalyzer), но она даёт ложные срабатывания:
    например, "столенок" распознаётся как известное слово через
    DictionaryAnalyzer (вероятно, совпадает с редкой фамилией в словаре
    OpenCorpora — Столенок), хотя как диминутив от "стол" это не
    существует. morph.word_is_known() эмпирически точнее в таких случаях.

    Имя параметра для нестрогого сравнения е/ё отличается между версиями/
    форками библиотеки: в оригинальном pymorphy2 — "strict_ee", в
    pymorphy3 и некоторых сборках — просто "strict". Пробуем оба варианта
    по очереди, а не полагаемся на одно конкретное имя.
    """
    try:
        return morph.word_is_known(word, strict_ee=False)
    except TypeError:
        pass
    try:
        return morph.word_is_known(word, strict=False)
    except TypeError:
        return morph.word_is_known(word)


def get_noun_parse(word: str):
    """
    Возвращает разбор pymorphy2 с приоритетом на часть речи NOUN, а не
    просто самый вероятный разбор по score. Без этого при омонимии частей
    речи (например, "стекло" — существительное "стекло" или форма глагола
    "стечь"; "печь" — существительное или глагол) наивный parse(word)[0]
    может вернуть совсем не то, что нужно.

    Если существительное среди разборов вообще есть — берём его (при
    нескольких NOUN-разборах, напр. разные падежи одной словоформы —
    выбираем наиболее вероятный по score среди них, это не влияет на
    normal_form/gender, которые нам и нужны). Если существительного нет
    ни в одном разборе — возвращаем как есть, ничего умнее тут не сделать.
    """
    parses = morph.parse(word)
    noun_parses = [p for p in parses if "NOUN" in p.tag]
    if noun_parses:
        return max(noun_parses, key=lambda p: p.score)
    return parses[0]


SUFFIX_TABLE_PATH = "suffix_connotation_table.json"


# ---------------------------------------------------------------------------
# 1. Загрузка таблицы коннотаций
# ---------------------------------------------------------------------------

def load_connotation_table(path: str = SUFFIX_TABLE_PATH) -> dict:
    """Возвращает словарь {ключ_суффикса: запись_из_таблицы}."""
    with open(path, encoding="utf-8") as f:
        entries = json.load(f)
    return {entry["suffix"]: entry for entry in entries}


CONNOTATION_TABLE = load_connotation_table()

# Суффиксы, реально используемые генератором ниже (буквальное написание,
# которое приклеивается к основе) -> ключ записи в таблице коннотаций.
# Один ключ таблицы покрывает целую орфографическую группу вариантов
# (см. поле "orth_variants" в JSON), поэтому здесь сведение many-to-one.
SUFFIX_TAG_MAP = {
    # мужской род
    "ик": "ок", "чик": "ок", "ок": "ок", "ек": "ок", "ёк": "ок",
    "ец": "ец", "ичек": "ок", "ишко_masc": "ишк", "онок": "онок",
    # женский род
    "ка": "ок", "ечка": "ок", "очка": "ок", "ичка": "ок",
    "енька": "оньк", "онька": "оньк",
    "онка": "ишк", "ёнка": "ишк", "ёшка": "ёшк",
    "ушка_femn": "ушк_ambiguous",  # особый случай, см. resolve_connotation
    "улька": None,  # нет в словаре-источнике, фолбэк ниже
    # средний род
    "ко": "ок", "ышко": "ок", "ечко": "ок", "ице": "ец",
    "юшко": "ушк_affectionate", "ишко_neut": "ишк",
    # увеличительный (формально не диминутив, см. запись "ищ" в таблице —
    # коннотация намеренно не задана по умолчанию, решает LLM-фильтр)
    "ищ": "ищ", "ища": "ищ",
}


def resolve_connotation(suffix_tag: str) -> dict:
    """
    Возвращает {"connotation": ..., "note": ...} для суффикса,
    приклеенного генератором. Обрабатывает омонимию -ушк- (два разных
    значения в источнике: ласкательное и пренебрежительное) отдельно,
    т.к. по одной лишь форме суффикса нельзя выбрать вариант однозначно —
    это должен уточнить LLM-фильтр на следующем шаге.
    """
    table_key = SUFFIX_TAG_MAP.get(suffix_tag)

    if table_key == "ушк_ambiguous":
        aff = CONNOTATION_TABLE.get("ушк_affectionate")
        pej = CONNOTATION_TABLE.get("ушк_pejorative")
        return {
            "connotation": "неоднозначно (ласкательное/пренебрежительное)",
            "note": f"Омонимия в источнике: {aff['note']} | {pej['note']}",
        }

    if table_key is None:
        return {
            "connotation": "неизвестно",
            "note": "Суффикс отсутствует в словаре-источнике, коннотация не размечена.",
        }

    entry = CONNOTATION_TABLE.get(table_key)
    if entry is None:
        return {"connotation": "неизвестно", "note": "Ключ не найден в таблице."}

    return {"connotation": entry["connotation_primary"], "note": entry["note"]}


# ---------------------------------------------------------------------------
# 2. Морфонологические правила (чередования, типы основ)
# ---------------------------------------------------------------------------

PALATALIZATION = {
    "ск": "щ", "ст": "щ",
    "к": "ч", "г": "ж", "х": "ш", "ц": "ч",
}


def palatalize(stem: str) -> str:
    for cons, alt in sorted(PALATALIZATION.items(), key=lambda x: -len(x[0])):
        if stem.endswith(cons):
            return stem[: -len(cons)] + alt
    return stem


def analyze_stem(lemma: str, gender: str) -> tuple[str, str]:
    """Возвращает (основа, тип_основы: 'hard'|'soft')."""
    last = lemma[-1]

    if gender == "masc":
        if last in "ьй":
            return lemma[:-1], "soft"
        return lemma, "hard"

    if gender == "femn":
        if last == "а":
            return lemma[:-1], "hard"
        if last in ("я", "ь"):
            return lemma[:-1], "soft"

    if gender == "neut":
        if last == "о":
            return lemma[:-1], "hard"
        if last == "е":
            return lemma[:-1], "soft"
        if last == "я":
            # разносклоняемые на -мя (время, имя, семя, племя, темя,
            # знамя, вымя, бремя, пламя, стремя) — их всего 10 в русском
            # языке. Для полного словоизменения у них исторически
            # появляется инфикс -ен- (время -> времени), но для
            # словообразования диминутивов достаточно просто отбросить
            # конечную "я" (время -> "врем" + "ечко" = "времечко") —
            # тот же паттерн, что и для обычных существительных на "-е".
            return lemma[:-1], "soft"

    return lemma, "hard"


VOWELS = set("аеёиоуыэюя")


def is_single_vowel_insertion(naive_stem: str, candidate_stem: str) -> bool:
    """
    True, если candidate_stem получается из naive_stem вставкой ровно одной
    гласной буквы (классическая беглая гласная: окн -> окон, сосн -> сосен).
    Отсекает случаи, когда род.п. мн.ч. просто длиннее из-за обычного
    падежного окончания (море -> морей, кровать -> кроватей) — это не
    беглая гласная, а другая словоформа, и подставлять её как основу
    для суффиксации неверно.
    """
    if len(candidate_stem) != len(naive_stem) + 1:
        return False
    for i, ch in enumerate(candidate_stem):
        if ch not in VOWELS:
            continue
        if candidate_stem[:i] + candidate_stem[i + 1:] == naive_stem:
            return True
    return False


def get_fleeting_vowel_stem(lemma: str, gender: str, naive_stem: str) -> str | None:
    """
    Возвращает основу с восстановленной беглой гласной (окно -> окон-,
    сосна -> сосен-), если она отличается от наивно усечённой основы
    ровно на одну вставную гласную.

    Беглая гласная появляется в форме род. падежа мн. числа у существительных
    ср. и жен. рода, чья основа в им. падеже оканчивается на два согласных
    подряд. Берём готовую форму у pymorphy2 вместо того чтобы прописывать
    эти чередования вручную — pymorphy2 уже знает нужную парадигму
    словоизменения. Проверка is_single_vowel_insertion защищает от случаев,
    когда род.п. мн.ч. просто имеет другое окончание (море -> морей),
    что не является беглой гласной.

    Актуально только для femn/neut: у masc род. падеж мн.ч. обычно
    добавляет "-ов/-ев", а не даёт голую согласную основу.
    """
    if gender not in ("femn", "neut"):
        return None

    parsed = get_noun_parse(lemma)
    inflected = parsed.inflect({"gent", "plur"})
    if inflected is None:
        return None

    candidate_stem = inflected.word
    if candidate_stem.endswith("ь"):
        candidate_stem = candidate_stem[:-1]

    if is_single_vowel_insertion(naive_stem, candidate_stem):
        return candidate_stem
    return None


# ---------------------------------------------------------------------------
# 3. Генерация кандидатов по роду
# ---------------------------------------------------------------------------

def gen_masc(stem: str, kind: str) -> set[tuple[str, str]]:
    # Если основа оканчивается на велярный согласный (к/г/х/ц), в русском
    # языке чередование перед этими суффиксами ОБЯЗАТЕЛЬНО — "человекик"
    # так же не существует, как и "рукочка" (см. is_missing_required_
    # palatalization в palatalization_postfilter.py, где это уже
    # закодировано как жёсткое правило, не вероятностное). Раз мы всё
    # равно достоверно знаем, что stem+ending при наличии велярного
    # согласного заведомо неверно — не генерируем эту половину вообще,
    # экономя кандидатов и токены LLM-фильтра. Если основа НЕ оканчивается
    # на велярный (soft == stem) — палатализации нет, используем stem как
    # обычно.
    soft = palatalize(stem)
    base = soft if soft != stem else stem

    endings = {
        "ик": "ик", "чик": "чик", "ец": "ец", "ичек": "ичек",
        "ок": "ок", "ек": "ек", "ёк": "ёк",
        "ишко_masc": "ишко", "ищ": "ище",
    }

    forms = set()
    for tag, ending in endings.items():
        forms.add((base + ending, tag))

    # -онок/-ёнок всегда от палатализованной основы (как и раньше)
    forms.add((soft + "онок", "онок"))
    forms.add((soft + "ёнок", "онок"))

    return forms


def gen_femn(stem: str, kind: str) -> set[tuple[str, str]]:
    # Та же логика, что и в gen_masc: при наличии велярного согласного
    # (к/г/х/ц) на конце основы чередование обязательно — форма без
    # него ("рукочка") заведомо неверна, поэтому не генерируем её вообще,
    # а не полагаемся на постфильтр, чтобы отсеять её постфактум.
    soft = palatalize(stem)
    base = soft if soft != stem else stem

    endings = {
        "ка": "ка", "ечка": "ечка", "очка": "очка",
        "ушка_femn": "ушка", "улька": "улька",
        "онка": "онка", "ёнка": "ёнка", "ёшка": "ёшка",
        "онька": "онька", "енька": "енька",
        "ища": "ища",
    }

    forms = set()
    for tag, ending in endings.items():
        forms.add((base + ending, tag))

    if kind == "soft":
        forms.add((stem + "ичка", "ичка"))
    return forms


def gen_neut(stem: str, kind: str) -> set[tuple[str, str]]:
    soft = palatalize(stem)
    if kind == "hard":
        return {
            (stem + "ко", "ко"), (soft + "ышко", "ышко"),
            (soft + "ечко", "ечко"), (stem + "ице", "ице"),
            (stem + "ишко", "ишко_neut"),
            (stem + "ище", "ищ"),
            # суффикс -ц-/-це/-цо (дело -> дельце, слово -> словцо,
            # окно -> оконце): согласный перед "ц" иногда смягчается
            # (л -> ль в "дельце"), иногда нет (н без "ь" в "оконце") —
            # чередование лексически обусловлено и не сводится к простому
            # правилу, поэтому даём оба варианта (с "ь" и без) и обе
            # орфографические формы окончания (-це/-цо), решение — за
            # LLM-фильтром.
            (stem + "це", "ец"), (stem + "цо", "ец"),
            (stem + "ьце", "ец"), (stem + "ьцо", "ец"),
        }
    return {
        (stem + "юшко", "юшко"), (stem + "ечко", "ечко"),
        (stem + "ице", "ице"),
        (stem + "ище", "ищ"),
    }


# ---------------------------------------------------------------------------
# 4. Словарь исключений (иррегулярные основы, не покрытые правилами)
# ---------------------------------------------------------------------------

EXCEPTIONS: dict[str, list[tuple[str, str]]] = {
    "окно": [("окошко", "ышко"), ("оконце", "ец")],
    "ухо": [("ушко", "ко")],
    "дерево": [("деревце", "ец")],
    "мать": [("мамочка", "ечка")],
}


# ---------------------------------------------------------------------------
# 5. Главная функция
# ---------------------------------------------------------------------------

def gen_candidates(word: str) -> list[dict]:
    """
    Для леммы существительного возвращает список кандидатов-диминутивов:
    [{"form": ..., "suffix": ..., "connotation_hint": ..., "note": ...}, ...]

    Это ПЕРЕГЕНЕРАЦИЯ (overgeneration) — список заведомо содержит формы,
    которых в языке не существует. Следующий шаг пайплайна (LLM-фильтр)
    должен отсеять нереальные формы и подтвердить/уточнить коннотацию.
    """
    parsed = get_noun_parse(word)
    lemma = parsed.normal_form
    gender = parsed.tag.gender

    if gender not in ("masc", "femn", "neut"):
        return []

    stem, kind = analyze_stem(lemma, gender)

    # Беглая гласная (окно -> окон-, палка -> палок-, ложка -> ложек-,
    # кружка -> кружек-): вычисляем альтернативную основу по форме
    # род.п. мн.ч. ДО генерации суффиксов — она определяет, какая основа
    # вообще является структурно корректной для этого слова.
    #
    # ВАЖНО (исправленная логика): если беглая гласная есть, НАИВНАЯ
    # основа (без вставленной гласной) структурно неполноценна — её
    # палатализация тоже неверна: palatalize("ложк") даёт "ложч" (без
    # обязательной "е"), и любой суффикс на такой основе даёт брак вида
    # "ложчонка" вместо "ложечонка". Поэтому при наличии alt_stem вся
    # генерация суффиксов идёт ТОЛЬКО от неё (она уже включает гласную и
    # сама корректно палатализуется через тот же gen_femn/gen_neut) — а
    # наивная основа для таких слов вообще не используется.
    #
    # Раньше здесь была попытка ограничить alt_stem только суффиксом
    # "-ка/-ко" из опасения перед "двойным наслоением суффиксов"
    # (кружечочка). Проверка показала, что это ложная теория: структурно
    # "круж-еч"+"-очка" ничем не отличается от "круж-еч"+"-ка" — это
    # обычное однократное присоединение суффикса к корректной основе,
    # просто конкретная форма может не быть реальным словом. Решать,
    # какая именно комбинация реальна — задача AND-фильтрации и словарной
    # проверки, а не жёсткое исключение на этапе генерации.
    alt_stem = get_fleeting_vowel_stem(lemma, gender, stem)

    raw: set[tuple[str, str]] = set()
    if gender == "masc":
        raw |= gen_masc(stem, kind)
    elif gender == "femn":
        raw |= gen_femn(alt_stem if alt_stem else stem, kind)
    elif gender == "neut":
        raw |= gen_neut(alt_stem if alt_stem else stem, kind)

    raw |= set(EXCEPTIONS.get(lemma, []))

    # Орфографическая вариативность ё/е: в разговорном письме "ё" почти
    # всегда заменяется на "е" (актёр -> актерчик, а не актёрчик). Это не
    # другой суффикс и не другое слово, а просто вариант записи того же
    # слова — поэтому для каждой формы с "ё" добавляем дубль с "е",
    # с тем же тегом суффикса. Без этого сравнение с формами из реальных
    # текстов/опросов (где респонденты обычно пишут без "ё") будет
    # систематически давать ложный "форма не найдена".
    for form, suffix_tag in list(raw):
        if "ё" in form:
            raw.add((form.replace("ё", "е"), suffix_tag))

    result_by_form: dict[str, dict] = {}
    for form, suffix_tag in raw:
        if form == lemma:
            continue
        if form in result_by_form:
            continue  # форма уже добавлена под другим суффиксом (напр. -ек/-ёк после ё->е схлопнулись в одну строку)
        conn = resolve_connotation(suffix_tag)
        result_by_form[form] = {
            "form": form,
            "suffix": suffix_tag,
            "connotation_hint": conn["connotation"],
            "note": conn["note"],
            # Бесплатная, мгновенная, локальная проверка по словарю
            # OpenCorpora (встроен в pymorphy2, никакого HTTP не нужно).
            # True — сильный сигнал "слово точно существует". False —
            # НЕ означает, что слова нет: словарь не содержит всех
            # разговорных диминутивов, просто ничего не решаем по этому
            # полю здесь, финальное решение — дальше по пайплайну
            # (LLM-фильтр / build_dictionary.py).
            "in_opencorpora": is_in_dictionary(form),
        }
    result = list(result_by_form.values())

    return sorted(result, key=lambda x: x["form"])


