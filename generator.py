def gen_candidates(word: str) -> list[dict]:
    """
    Для леммы существительного возвращает список кандидатов-диминутивов:
    [{"form": ..., "suffix": ..., "connotation_hint": ..., "note": ...}, ...]

    Это ПЕРЕГЕНЕРАЦИЯ (overgeneration) — список заведомо содержит формы,
    которых в языке не существует. Следующий шаг пайплайна (LLM-фильтр)
    должен отсеять нереальные формы и подтвердить/уточнить коннотацию.
    """
    parsed = get_noun_parse(word)
    lemma = parsed.normal_form
    gender = parsed.tag.gender

    if gender not in ("masc", "femn", "neut"):
        return []

    stem, kind = analyze_stem(lemma, gender)
    if gender == "masc":
        stem = MASC_STEM_EXCEPTIONS.get(lemma, stem)

    # Беглая гласная (окно -> окон-, палка -> палок-, ложка -> ложек-,
    # кружка -> кружек-): вычисляем альтернативную основу по форме
    # род.п. мн.ч. ДО генерации суффиксов — она определяет, какая основа
    # вообще является структурно корректной для этого слова.
    #
    # ВАЖНО (исправленная логика): если беглая гласная есть, НАИВНАЯ
    # основа (без вставленной гласной) структурно неполноценна — её
    # палатализация тоже неверна: palatalize("ложк") даёт "ложч" (без
    # обязательной "е"), и любой суффикс на такой основе даёт брак вида
    # "ложчонка" вместо "ложечонка". Поэтому при наличии alt_stem вся
    # генерация суффиксов идёт ТОЛЬКО от неё (она уже включает гласную и
    # сама корректно палатализуется через тот же gen_femn/gen_neut) — а
    # наивная основа для таких слов вообще не используется.
    #
    # Раньше здесь была попытка ограничить alt_stem только суффиксом
    # "-ка/-ко" из опасения перед "двойным наслоением суффиксов"
    # (кружечочка). Проверка показала, что это ложная теория: структурно
    # "круж-еч"+"-очка" ничем не отличается от "круж-еч"+"-ка" — это
    # обычное однократное присоединение суффикса к корректной основе,
    # просто конкретная форма может не быть реальным словом. Решать,
    # какая именно комбинация реальна — задача AND-фильтрации и словарной
    # проверки, а не жёсткое исключение на этапе генерации.
    alt_stem = get_fleeting_vowel_stem(lemma, gender, stem)

    raw: set[tuple[str, str]] = set()
    if gender == "masc":
        short_stem = None if lemma in MASC_STEM_EXCEPTIONS else get_masc_fleeting_stem(lemma, stem)
        raw |= gen_masc(stem, kind, lemma, animacy=parsed.tag.animacy, short_stem=short_stem)
    elif gender == "femn":
        raw |= gen_femn(stem, kind)
        if alt_stem and alt_stem != stem:
            raw |= gen_femn(alt_stem, kind)
    elif gender == "neut":
        raw |= gen_neut(stem, kind)
        if alt_stem and alt_stem != stem:
            raw |= gen_neut(alt_stem, kind)

    raw |= set(EXCEPTIONS.get(lemma, []))

    # «ё» всегда ударная, ударение в слове одно — форма с двумя «ё»
    # заведомо ошибочна (сестёр- + -ёнка = "сестёрёнка"). Отсекаем ДО
    # генерации е-дублей, иначе из неё вырастет "сестеренка".
    raw = {(form, tag) for form, tag in raw if form.count("ё") <= 1}

    # Орфографическая вариативность ё/е: в разговорном письме "ё" почти
    # всегда заменяется на "е" (актёр -> актерчик, а не актёрчик). Это не
    # другой суффикс и не другое слово, а просто вариант записи того же
    # слова — поэтому для каждой формы с "ё" добавляем дубль с "е",
    # с тем же тегом суффикса. Без этого сравнение с формами из реальных
    # текстов/опросов (где респонденты обычно пишут без "ё") будет
    # систематически давать ложный "форма не найдена".
    for form, suffix_tag in list(raw):
        if "ё" in form:
            raw.add((form.replace("ё", "е"), suffix_tag))

    result_by_form: dict[str, dict] = {}
    # Формы из EXCEPTIONS подтверждены вручную — фильтр падежных
    # омографов к ним не применяем (дедок = и диминутив, и род.п. мн.ч. от "дедка").
    exception_forms = {f for f, _ in EXCEPTIONS.get(lemma, [])}

    result_by_form: dict[str, dict] = {}
    blocked = _BLOCKLIST_NORM.get(lemma.replace("ё", "е"), set())
    for form, suffix_tag in raw:
        if form == lemma or form.replace("ё", "е") in blocked:       # ← ЗАМЕНЁННАЯ строка
            continue
        if form not in exception_forms and is_inflected_form_of_other_word(form):
            continue
        if form in result_by_form:
            continue  # форма уже добавлена под другим суффиксом (напр. -ек/-ёк после ё->е схлопнулись в одну строку)
        # -онок1 (детёныш, нейтр.) vs -онок2 (экспрессия): по одушевлённости
        # леммы — слонёнок/котёнок vs бочонок/голосёнок.
        conn_tag = "онок_young" if suffix_tag == "онок" and parsed.tag.animacy == "anim" else suffix_tag
        conn = resolve_connotation(conn_tag)
        result_by_form[form] = {
            "form": form,
            "suffix": suffix_tag,
            "connotation_hint": conn["connotation"],
            "note": conn["note"],
            # Бесплатная, мгновенная, локальная проверка по словарю
            # OpenCorpora (встроен в pymorphy2, никакого HTTP не нужно).
            # True — сильный сигнал "слово точно существует". False —
            # НЕ означает, что слова нет: словарь не содержит всех
            # разговорных диминутивов, просто ничего не решаем по этому
            # полю здесь, финальное решение — дальше по пайплайну
            # (LLM-фильтр / build_dictionary.py).
            "in_opencorpora": is_in_dictionary(form),
        }
    # Подавление избыточных орфографических пар (различие ровно в "ь":
    # свинка/свинька) ДО отправки в LLM-фильтр — если словарь подтверждает
    # только одну из пары, вторую вообще не генерируем: чем меньше в
    # списке кандидатов правдоподобно звучащих, но лишних форм, тем
    # меньше почвы для синхронных ошибок AND-фильтрации (LLM физически
    # не может согласиться на форму, которой нет в списке).
    #
    # Если подтверждены ОБЕ или НИ ОДНА — не решаем за словарь, оставляем
    # обе формы дальше по пайплайну (LLM/эксперт решают), как и раньше.
    all_forms = list(result_by_form.keys())
    suppressed: set[str] = set()
    for i in range(len(all_forms)):
        for j in range(i + 1, len(all_forms)):
            f1, f2 = all_forms[i], all_forms[j]
            if not differs_only_by_soft_sign(f1, f2):
                continue
            d1 = result_by_form[f1]["in_opencorpora"]
            d2 = result_by_form[f2]["in_opencorpora"]
            if d1 and not d2:
                suppressed.add(f2)
            elif d2 and not d1:
                suppressed.add(f1)
            # оба или ни одного в словаре — ничего не подавляем

    for f in suppressed:
        del result_by_form[f]

    result = list(result_by_form.values())

    return sorted(result, key=lambda x: x["form"])


