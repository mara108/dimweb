# Чередование перед -онок-/-ёнок- ("третья палатализация" + сюда же
# исторически примкнувшие случаи) — ОТДЕЛЬНАЯ, не связанная с общей
# palatalize() таблица. Причина изоляции: если добавить "д"->"ж" в общую
# PALATALIZATION, это сломает ВСЕ остальные суффиксы для основ на "д"
# (сад -> "сажик"/"сажок" вместо "садик"/"садок") — palatalize()
# используется всеми суффиксами в gen_masc, а не только -онок-/-ёнок-.
#
# Список НЕ претендует на полноту: чередование здесь нерегулярно даже
# среди слов, где оно вообще есть (кот->котёнок БЕЗ чередования,
# гусь->гусёнок БЕЗ чередования, при этом медведь->медвежонок И
# верблюд->верблюжонок — С чередованием д->ж). Правило добавляет только
# то согласное, для которого чередование системно наблюдается у
# нескольких разных слов (д->ж); случаи, не сводящиеся к замене одной
# согласной (см. ONOK_LEMMA_EXCEPTIONS ниже), решаются отдельно.
ONOK_EXTRA_PALATALIZATION = {"д": "ж"}


def onok_palatalize(stem: str) -> str:
    for cons, alt in ONOK_EXTRA_PALATALIZATION.items():
        if stem.endswith(cons):
            return stem[:-len(cons)] + alt
    return palatalize(stem)  # общие к/г/х/ц/ск/ст по-прежнему применимы (волк->волчонок)

def gen_masc(stem: str, kind: str, lemma: str | None = None, animacy: str | None = None,
                 short_stem: str | None = None) -> set[tuple[str, str]]:
    # Если основа оканчивается на велярный согласный (к/г/х/ц), в русском
    # языке чередование перед этими суффиксами ОБЯЗАТЕЛЬНО — "человекик"
    # так же не существует, как и "рукочка" (см. is_missing_required_
    # palatalization в palatalization_postfilter.py, где это уже
    # закодировано как жёсткое правило, не вероятностное). Раз мы всё
    # равно достоверно знаем, что stem+ending при наличии велярного
    # согласного заведомо неверно — не генерируем эту половину вообще,
    # экономя кандидатов и токены LLM-фильтра. Если основа НЕ оканчивается
    # на велярный (soft == stem) — палатализации нет, используем stem как
    # обычно.
    soft = palatalize(stem)
    base = soft if soft != stem else stem

    endings = {
        "ик": "ик", "чик": "чик", "ец": "ец", "ичек": "ичек",
        "ищ": "ище",
    }

    forms = set()
    for tag, ending in endings.items():
        forms.add((base + ending, tag))

    # Диминутив сохраняет твёрдость/мягкость основы: лес -> лесок,
    # но пень -> пенёк -> пенёчек, конь -> конёк. После шипящих — всегда
    # «о» (дружок, снежок). Второй вариант заведомо неверен:
    # "пенок" — это вообще род.п. мн.ч. от "пенка".
    if kind == "soft" and base[-1] not in "жчшщ":
        ok_suffix, ochek_suffix = "ёк", "ёчек"
    else:
        ok_suffix, ochek_suffix = "ок", "очек"
    forms.add((base + ok_suffix, ok_suffix))
    forms.add((base + ochek_suffix, ochek_suffix))

    # -ек (безударный) — только после шипящих из чередования: орешек,
    # горошек. От прочих основ даёт мусор ("лесек", "слонек").
    if base[-1] in "жчшщ":
        forms.add((base + "ек", "ек"))
    # -ишка (мальчишка, зайчишка, воришка) — вариант "-ишко" (домишко,
    # городишко) для ОДУШЕВЛЁННЫХ существительных. Не универсальный
    # суффикс для всех masc-слов: неодушевлённые предметы образуют
    # только "-ишко" (окончание среднего рода по форме, хотя само слово
    # мужского рода), а одушевлённые (обычно люди/животные) — "-ишка"
    # (окончание женского рода по форме). Оба варианта не
    # взаимозаменяемы лексически, поэтому не генерируем "-ишка" вслепую
    # для всех — только когда pymorphy2 подтверждает одушевлённость
    # (animacy передаётся из gen_candidates, где уже есть разбор слова).

    # Беглая гласная (пень -> пн-): перед суффиксами на гласную часто
    # выпадает (пнище), но не всегда (ротище, лобище) — даём оба варианта.
    if short_stem:
        short_base = palatalize(short_stem)
        forms.add((short_base + "ище", "ищ"))
        forms.add((short_base + "ишко", "ишко_masc"))
        if animacy == "anim":
            forms.add((short_base + "ишка", "ишка_masc"))
        else:
            forms.add((short_base + "ишко", "ишко_masc"))
    if animacy == "anim":
        forms.add((base + "ишка", "ишка_masc"))
    else:
        forms.add((base + "ишко", "ишко_masc"))

    # -чик после твёрдой "л" нередко идёт с мягким знаком: стул ->
    # стульчик (а не "стулчик"), колокол -> колокольчик. Это не
    # фонологическое правило: у других основ мягкого знака нет (вагон ->
    # вагончик, стакан -> стаканчик, диван -> диванчик), поэтому
    # предсказать по основе, нужен ли "ь", нельзя. Генерируем ОБА
    # варианта (…лчик и …льчик) и оставляем выбор дальше по пайплайну:
    # пара, различающаяся только мягким знаком, уже обрабатывается в
    # gen_candidates (differs_only_by_soft_sign) — если словарь знает
    # только одну форму, вторая отбрасывается ещё до LLM. Только для
    # твёрдых основ (kind == "hard"): у мягких "ь" уже есть в лемме.
    if kind == "hard" and base.endswith("л"):
        forms.add((base + "ьчик", "чик"))
    # -ёнок систематически от основы без беглой гласной: львёнок, орлёнок
    onok_base = onok_palatalize(short_stem or stem)
    # Орфография: -онок только после шипящих (медвежонок, волчонок),
    # иначе -ёнок (котёнок, слонёнок). Второй вариант заведомо неверен.
    onok_suffix = "онок" if onok_base[-1] in "жчшщ" else "ёнок"
    forms.add((onok_base + onok_suffix, "онок"))
    return forms


def gen_femn(stem: str, kind: str) -> set[tuple[str, str]]:
    # Та же логика, что и в gen_masc: при наличии велярного согласного
    # (к/г/х/ц) на конце основы чередование обязательно — форма без
    # него ("рукочка") заведомо неверна, поэтому не генерируем её вообще,
    # а не полагаемся на постфильтр, чтобы отсеять её постфактум.
    # Основа на -ск (доска, миска, маска): от неё самой реален только
    # -ечка с ск->щ (дощечка). Остальные формы (досочка, мисочка) строятся
    # от основы с беглой гласной (досок-, мисок-) — отдельным вызовом.
    if stem.endswith("ск"):
        return set()
    soft = palatalize(stem)
    base = soft if soft != stem else stem

    endings = {
        "ка": "ка", "ечка": "ечка", "очка": "очка",
        "ушка_femn": "ушка", "улька": "улька",
        "ёшка": "ёшка",
        "онька": "онька", "енька": "енька",
        "ища": "ища",
    }

    forms = set()
    for tag, ending in endings.items():
        forms.add((base + ending, tag))

    # То же правило для -онка/-ёнка: ручонка, но сестрёнка.
    onka = "онка" if base[-1] in "жчшщ" else "ёнка"
    forms.add((base + onka, onka))
    if kind == "soft":
        forms.add((stem + "ичка", "ичка"))
        # Орфографическое смягчение гласной в суффиксе после мягкой
        # основы (земля -> земель- -> земелЬка, земелЮшка), а НЕ
        # чередование согласного (для этого явления palatalize не
        # подходит — согласная не меняется, меняется гласная в самом
        # суффиксе, плюс восстанавливается "ь"). Раньше эти варианты
        # не генерировались вовсе — "земелка"/"земелушка" были
        # единственными кандидатами, оба орфографически неверны.
        forms.add((stem + "ька", "ька"))
        forms.add((stem + "юшка", "ушка_femn"))
    return forms



def gen_neut(stem: str, kind: str) -> set[tuple[str, str]]:
    soft = palatalize(stem)
    if kind == "hard":
        return {
            (stem + "ко", "ко"), (soft + "ышко", "ышко"),
            (soft + "ечко", "ечко"), (stem + "ице", "ице"),
            (stem + "ишко", "ишко_neut"),
            (stem + "ище", "ищ"),
            # суффикс -ц-/-це/-цо (дело -> дельце, слово -> словцо,
            # окно -> оконце): согласный перед "ц" иногда смягчается
            # (л -> ль в "дельце"), иногда нет (н без "ь" в "оконце") —
            # чередование лексически обусловлено и не сводится к простому
            # правилу, поэтому даём оба варианта (с "ь" и без) и обе
            # орфографические формы окончания (-це/-цо), решение — за
            # LLM-фильтром.
            (stem + "це", "ец"), (stem + "цо", "ец"),
            (stem + "ьце", "ец"), (stem + "ьцо", "ец"),
        }
    return {
        (stem + "юшко", "юшко"), (stem + "ечко", "ечко"),
        (stem + "ице", "ице"),
        (stem + "ище", "ищ"),
    }


